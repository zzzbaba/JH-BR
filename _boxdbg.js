const fs=require('fs'),path=require('path'),crypto=require('crypto');
const { chromium } = require('playwright-core');
const BASE='http://127.0.0.1:8123';
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
(async()=>{
  const at=await fetch(BASE+'/api/admin/login',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({password:'jianghan'})}).then(r=>r.json()).then(j=>j.token);
  const user='bx'+Date.now().toString().slice(-5);
  const tk=await fetch(BASE+'/api/register',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({username:user,password:'1234'})}).then(r=>r.json()).then(j=>j.token);
  const ng=await fetch(BASE+'/api/newgame',{method:'POST',headers:{'Content-Type':'application/json','Authorization':'Bearer '+tk},body:JSON.stringify({name:'箱测'})}).then(r=>r.json());
  console.log('newgame:',ng.ok, ng.msg||'');
  const f=path.join('store','saves',crypto.createHash('md5').update(user).digest('hex').slice(0,16)+'.json');
  const s=JSON.parse(fs.readFileSync(f,'utf8'));
  s.char.bag=[]; for(let i=0;i<16;i++) s.char.bag.push({id:'m_scrap',n:1});
  s.char.scene='box';
  s.char.pending={items:[{id:'med01',n:2}],text:'墙角堆着的木箱。',zoneName:'十号地'};
  fs.writeFileSync(f,JSON.stringify(s,null,2));
  const st=await fetch(BASE+'/api/state',{headers:{Authorization:'Bearer '+tk}}).then(r=>r.json());
  console.log('state:', st.hasSave, st.state&&st.state.scene, 'pending?', !!(st.state&&st.state.pending));
  const b=await chromium.launch({executablePath:'C://Program Files\\Google\\Chrome\\Application\\chrome.exe',headless:true});
  const p=await (await b.newContext({viewport:{width:1440,height:900}})).newPage();
  const errs=[];p.on('pageerror',e=>errs.push(e.message));
  await p.goto(BASE,{waitUntil:'networkidle'});
  await p.evaluate(t=>localStorage.setItem('br_token',t),tk);
  await p.evaluate(u=>localStorage.setItem('br_user',u),user);
  await p.reload({waitUntil:'networkidle'});await sleep(1500);
  console.log('modal:', await p.evaluate(()=>({hidden:document.querySelector('#modal').classList.contains('hidden'),title:(document.querySelector('.m-title')||{}).textContent||'', wait:!document.querySelector('#waitScreen').classList.contains('hidden'), game:!document.querySelector('#gameScreen').classList.contains('hidden')})));
  console.log('错误:',errs.slice(0,3));
  await b.close();
})();
